// 主题说明：C++ 运算符与表达式 —— 算术（整除/取模/浮点）、比较与逻辑短路、
//           位运算（与/或/异或/取反/移位）、前置后置自增、三目运算符、优先级。
// 运行命令：./cpp/basics/build/03_operator
// 预期输出（关键行）：
//   7 / 2 = 3（整除），7 % 2 = 1（取模），7.0 / 2 = 3.5（浮点除）
//   0xc & 0xa = 0x8, 0xc | 0xa = 0xe, 0xc ^ 0xa = 0x6, ~0xc = 0xfffffff3
//   1 << 4 = 0x10, 0xc >> 2 = 0x3
//   前置：先加再用，i = 6，pre = 6
//   后置：先用后加，返回 5，之后 j = 6
//   较大者 = 7（三目运算符）
//   1 + 2 * 3 = 7；(1 + 2) * 3 = 9

#include <iostream>

int main() {
    // ---- 1. 算术运算符：整除与取模是初学者第一个坑 ----
    std::cout << "7 / 2 = " << 7 / 2 << "（整除），7 % 2 = " << 7 % 2
              << "（取模），7.0 / 2 = " << 7.0 / 2 << "（浮点除）\n";
    // 结论：两个 int 相除还是 int，想要小数必须先把一侧变成浮点

    // ---- 2. 比较与逻辑运算符：&& 和 || 有“短路”求值 ----
    int x = 10;
    if (x > 0 && x < 100) {
        std::cout << "0 < x < 100 需要写成两个比较再 && 连接\n";
    }
    int* p = nullptr;               // 指针判空是短路的经典应用
    if (p != nullptr && *p > 0) {   // p 为空时 && 右侧不会被求值，解引用安全
        std::cout << "不会执行到这里\n";
    } else {
        std::cout << "短路求值：p 为空，右侧 *p 未被求值\n";
    }

    // ---- 3. 位运算：对整数的二进制位逐位操作（用 unsigned 语义最清晰）----
    unsigned ua = 0xc;  // 1100
    unsigned ub = 0xa;  // 1010
    std::cout << std::hex << std::showbase  // 切到十六进制带前缀输出
              << "0xc & 0xa = " << (ua & ub) << ", 0xc | 0xa = " << (ua | ub)
              << ", 0xc ^ 0xa = " << (ua ^ ub) << ", ~0xc = " << ~ua << "\n"
              << "1 << 4 = " << (1u << 4) << ", 0xc >> 2 = " << (ua >> 2)
              << std::noshowbase << std::dec << "\n";  // 切回十进制
    // 提醒：位运算优先级低于比较，写 (flags & MASK) == 0 必须带括号

    // ---- 4. 自增自减：前置先用后……不，前置“先加再用”，后置“先用后加” ----
    int i = 5;
    int pre = ++i;  // i 先变成 6，pre 拿到 6
    std::cout << "前置：先加再用，i = " << i << "，pre = " << pre << "\n";
    int j = 5;
    int post = j++;  // post 先拿到 5，j 随后变成 6
    std::cout << "后置：先用后加，返回 " << post << "，之后 j = " << j << "\n";

    // ---- 5. 三目运算符：表达式里的 if-else ----
    int a = 3, b = 7;
    int bigger = a > b ? a : b;
    std::cout << "较大者 = " << bigger << "（三目运算符）\n";

    // ---- 6. 优先级：乘除高于加减，括号永远是最清晰的写法 ----
    std::cout << "1 + 2 * 3 = " << 1 + 2 * 3 << "；(1 + 2) * 3 = " << (1 + 2) * 3 << "\n";

    return 0;
}
