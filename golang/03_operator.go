// 主题说明：Go 运算符与表达式 —— 算术（整数相除截断）、比较、逻辑短路、
//           位运算（含 Go 特有的 &^ 按位清零）、++/-- 是语句不是表达式、运算符优先级。
// 运行命令：go run golang/03_operator.go
// 预期输出（关键行）：
//   17 / 5 = 3 （整数相除直接截断小数）
//   false && touch("A") = false
//   true || touch("B") = true   （短路：两行均无"右侧被求值"打印）
//   x &^ y = 0100 (4)（y 为 1 的位被清零）
//   n++ 之后 n = 6
//   1<<2+1 = 5 （<< 高于 +：先 1<<2=4，再 4+1）
package main

import "fmt"

// touch 用于演示逻辑短路：只有真正被求值时才会打印
func touch(tag string) bool {
    fmt.Println("    （右侧", tag, "被求值了）")
    return true
}

func main() {
    // 知识点 1：算术运算符 —— 重点：两个整数相除仍是整数（截断小数，不是四舍五入）
    a, b := 17, 5
    fmt.Println("[1] 17 + 5 =", a+b, " 17 - 5 =", a-b, " 17 * 5 =", a*b)
    fmt.Println("    17 / 5 =", a/b, "（整数相除直接截断小数）")
    fmt.Println("    17 % 5 =", a%b, "（取余）")
    fmt.Println("    17 / 5.0 =", float64(a)/float64(b), "（想要小数必须先转换类型）")

    // 知识点 2：比较运算符 —— 结果都是 bool
    fmt.Println("[2] 3 > 2 =", 3 > 2, " 2 <= 1 =", 2 <= 1, " 1 != 2 =", 1 != 2)
    fmt.Println("    \"go\" == \"go\" =", "go" == "go", "（字符串按值比较）")

    // 知识点 3：逻辑运算符 && 与 || 都短路 —— 左边已定结果，右边就不再求值
    fmt.Println("[3] false && touch(\"A\") =", false && touch("A")) // 短路：右侧不执行
    fmt.Println("    true || touch(\"B\") =", true || touch("B"))   // 短路：右侧不执行
    fmt.Println("    !true =", !true)

    // 知识点 4：位运算 —— & | ^ << >>，以及 Go 特有的 &^（按位清零）
    x, y := 0b1100, 0b1010 // 二进制字面量：12 与 10
    fmt.Printf("[4] x=%04b(%d)  y=%04b(%d)\n", x, x, y, y)
    fmt.Printf("    x & y  = %04b (%d)\n", x&y, x&y)   // 按位与
    fmt.Printf("    x | y  = %04b (%d)\n", x|y, x|y)   // 按位或
    fmt.Printf("    x ^ y  = %04b (%d)\n", x^y, x^y)   // 按位异或
    fmt.Printf("    x &^ y = %04b (%d)（y 为 1 的位被清零）\n", x&^y, x&^y)
    fmt.Printf("    x << 2 = %04b (%d)  x >> 2 = %04b (%d)\n", x<<2, x<<2, x>>2, x>>2)
    fmt.Printf("    ^x = %d（一元 ^ 是按位取反：^x = -x - 1）\n", ^x)

    // 知识点 5：++ / -- 是"语句"不是"表达式" —— 只能独立成句
    n := 5
    n++ // 合法：一条自增语句；不存在 ++n 前缀写法，也没有 c := n++ 这种用法
    fmt.Println("[5] n++ 之后 n =", n)
    n--
    fmt.Println("    n-- 之后 n =", n)

    // 知识点 6：运算符优先级 —— 同级为一档，从高到低：* / % << >> & &^ 　高于　+ - | ^
    //  　高于　比较(== != < <= > >=) 　高于　&& 　高于　||（单目 ! ^ 最高，拿不准就加括号）
    fmt.Println("[6] 1+2*3 =", 1+2*3, "（先乘除后加减）")
    fmt.Println("    (1+2)*3 =", (1+2)*3, "（括号改变优先级）")
    fmt.Println("    1<<2+1 =", 1<<2+1, "（<< 高于 +：先 1<<2=4，再 4+1）")
    fmt.Println("    5&3 == 1 =", 5&3 == 1, "（& 高于 ==：先 5&3=1，再比较）")
    fmt.Println("    10 > 3 && 2 > 3 || true =", 10 > 3 && 2 > 3 || true, "（&& 高于 ||）")
}
